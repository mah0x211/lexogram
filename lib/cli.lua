-- lexogram.cli: the lexogram command (bin/lexogram runs main).
--
--   lexogram check GRAMMAR
--   lexogram merge GRAMMAR
--   lexogram compile GRAMMAR [-o FILE]
--   lexogram parse [--format json|tree] GRAMMAR [FILE]
--
-- GRAMMAR is a grammar file, a built-in grammar ("lexogram:name"), or a
-- compiled grammar that compile saved (a file that starts with the header
-- of lexogram.dump), which is read back with lexogram.undump. check
-- writes the diagnostics, one per line with the severity, the code, the
-- path and the message separated by tabs; merge writes the source of
-- lexogram.merge; compile writes the source of lexogram.dump; parse
-- writes the result of lexogram.parse of FILE, or of the standard input,
-- as JSON (the name and version of the grammar, the kinds, the events and
-- the errors) or as a tree for reading.
--
-- main returns the exit code: 0 on success, 1 when the grammar or the
-- source has errors, 2 on a wrong use or a file that cannot be read or
-- written. Warnings go to the standard error, except those of check.
local assert = assert
local type = type
local pairs = pairs
local ipairs = ipairs
local tostring = tostring
local byte = string.byte
local format = string.format
local sub = string.sub
local concat = table.concat
local sort = table.sort
local io = io
local io_open = io.open
local lexogram = require('lexogram')
local decode = require('lexogram.utf8').decode

local USAGE = [[
usage: lexogram check GRAMMAR
       lexogram merge GRAMMAR
       lexogram compile GRAMMAR [-o FILE]
       lexogram parse [--format json|tree] GRAMMAR [FILE]

GRAMMAR is a grammar file, a built-in grammar (lexogram:NAME), or a
compiled grammar saved by compile.
]]

-- the header that lexogram.dump writes first
local DUMP_HEADER = '-- Generated by lexogram.dump.'

-- event opcodes (see lexogram.analyzer)
local TOKEN, ENTER, EXIT = 1, 2, 3

--- read returns the content of the file at pathname, or nil and an error
--- message.
--- @param env table
--- @param pathname string
--- @return string? content
--- @return string? err
local function read(env, pathname)
    local f, err = env.open(pathname, 'rb')
    if not f then
        return nil, err
    end
    local content = f:read('*a')
    f:close()
    if not content then
        return nil, pathname .. ': cannot read'
    end
    return content
end

--- diagnostic returns a diagnostic as one line of tab-separated fields.
--- @param d table
--- @return string
local function diagnostic(d)
    return concat({
        tostring(d.severity),
        tostring(d.code),
        tostring(d.path),
        tostring(d.message),
    }, '\t') .. '\n'
end

--- open_grammar returns the grammar or the compiled grammar that name
--- refers to: "grammar" and the grammar with the warnings of its mixins,
--- or "compiled" and the compiled grammar; or nil, an error message and the
--- exit code.
--- @param env table
--- @param name string
--- @return string? kind
--- @return table|string value
--- @return table|integer extra warnings, or the exit code
local function open_grammar(env, name)
    if sub(name, 1, 9) ~= 'lexogram:' then
        local content, err = read(env, name)
        if not content then
            return nil, err, 2
        elseif sub(content, 1, #DUMP_HEADER) == DUMP_HEADER then
            local compiled
            compiled, err = lexogram.undump(content)
            if not compiled then
                return nil, name .. ': ' .. err, 1
            end
            return 'compiled', compiled
        end
    end
    local grammar, err, warnings = lexogram.load(name)
    if not grammar then
        return nil, err, 1
    end
    return 'grammar', grammar, warnings or {}
end

--- compile_grammar returns the compiled grammar of grammar, writing the
--- warnings of its mixins and the diagnostics to the standard error, or
--- nil and the exit code.
--- @param env table
--- @param grammar table
--- @param warnings table[]
--- @return table? compiled
--- @return integer? code
local function compile_grammar(env, grammar, warnings)
    for _, w in ipairs(warnings) do
        env.stderr:write(diagnostic(w))
    end
    local compiled, diagnostics = lexogram.compile(grammar)
    for _, d in ipairs(diagnostics) do
        env.stderr:write(diagnostic(d))
    end
    if not compiled then
        return nil, 1
    end
    return compiled
end

--- compiled_grammar returns the compiled grammar that name refers to,
--- writing the warnings to the standard error, or nil and the exit code.
--- @param env table
--- @param name string
--- @return table? compiled
--- @return integer? code
local function compiled_grammar(env, name)
    local kind, value, extra = open_grammar(env, name)
    if not kind then
        env.stderr:write(value, '\n')
        return nil, extra
    elseif kind == 'compiled' then
        return value
    end
    return compile_grammar(env, value, extra)
end

-- commands

--- check writes the diagnostics of the grammar name.
local function check(env, args)
    if #args ~= 1 then
        return nil
    end
    local kind, value, extra = open_grammar(env, args[1])
    if not kind then
        env.stderr:write(value, '\n')
        return extra
    elseif kind == 'compiled' then
        -- the grammar was checked when it was compiled, and undump has read
        -- it back
        return 0
    end
    for _, w in ipairs(extra) do
        env.stdout:write(diagnostic(w))
    end
    local compiled, diagnostics = lexogram.compile(value)
    for _, d in ipairs(diagnostics) do
        env.stdout:write(diagnostic(d))
    end
    return compiled and 0 or 1
end

--- merge writes the source of the grammar name merged.
local function merge(env, args)
    if #args ~= 1 then
        return nil
    end
    local name = args[1]
    if sub(name, 1, 9) ~= 'lexogram:' then
        local content, err = read(env, name)
        if not content then
            env.stderr:write(err, '\n')
            return 2
        elseif sub(content, 1, #DUMP_HEADER) == DUMP_HEADER then
            env.stderr:write(name, ': a compiled grammar cannot be merged\n')
            return 2
        end
    end
    local source, err, warnings = lexogram.merge(name)
    if not source then
        env.stderr:write(err, '\n')
        return 1
    end
    for _, w in ipairs(warnings) do
        env.stderr:write(diagnostic(w))
    end
    env.stdout:write(source)
    return 0
end

--- compile writes the compiled grammar name as the source of dump, to the
--- file of -o or to the standard output.
local function compile(env, args)
    local name, out
    local i = 1
    while i <= #args do
        local a = args[i]
        if a == '-o' then
            if out or not args[i + 1] then
                return nil
            end
            out = args[i + 1]
            i = i + 2
        elseif name then
            return nil
        else
            name = a
            i = i + 1
        end
    end
    if not name then
        return nil
    end
    local kind, value, extra = open_grammar(env, name)
    if not kind then
        env.stderr:write(value, '\n')
        return extra
    elseif kind == 'compiled' then
        env.stderr:write(name, ': already a compiled grammar\n')
        return 2
    end
    local compiled, code = compile_grammar(env, value, extra)
    if not compiled then
        return code
    end
    -- a compiled grammar holds plain data only, which dump writes
    local text = assert(lexogram.dump(compiled))
    if not out then
        env.stdout:write(text)
        return 0
    end
    local f, err = env.open(out, 'wb')
    if not f then
        env.stderr:write(err, '\n')
        return 2
    end
    f:write(text)
    f:close()
    return 0
end

-- output of parse

--- quote returns s in double quotes, with the bytes that are not printable
--- ASCII escaped as \n, \r, \t or \ddd, the same on every runtime.
--- @param s string
--- @return string
local function quote(s)
    local out = {
        '"',
    }
    for i = 1, #s do
        local b = byte(s, i)
        if b == 0x22 then
            out[#out + 1] = '\\"'
        elseif b == 0x5C then
            out[#out + 1] = '\\\\'
        elseif b == 0x0A then
            out[#out + 1] = '\\n'
        elseif b == 0x0D then
            out[#out + 1] = '\\r'
        elseif b == 0x09 then
            out[#out + 1] = '\\t'
        elseif b < 0x20 or b > 0x7E then
            out[#out + 1] = format('\\%03d', b)
        else
            out[#out + 1] = sub(s, i, i)
        end
    end
    out[#out + 1] = '"'
    return concat(out)
end

--- json_string returns s as a JSON string, or nil and an error message if
--- s is not valid UTF-8.
--- @param s string
--- @return string? json
--- @return string? err
local function json_string(s)
    local out = {
        '"',
    }
    local pos, len = 1, #s
    while pos <= len do
        local b = byte(s, pos)
        if b == 0x22 then
            out[#out + 1] = '\\"'
        elseif b == 0x5C then
            out[#out + 1] = '\\\\'
        elseif b == 0x0A then
            out[#out + 1] = '\\n'
        elseif b == 0x0D then
            out[#out + 1] = '\\r'
        elseif b == 0x09 then
            out[#out + 1] = '\\t'
        elseif b < 0x20 then
            out[#out + 1] = format('\\u%04x', b)
        elseif b < 0x80 then
            out[#out + 1] = sub(s, pos, pos)
        else
            local cp, n = decode(s, pos)
            if not cp then
                return nil, 'invalid UTF-8 in ' .. quote(s) .. ': ' .. n
            end
            out[#out + 1] = sub(s, pos, pos + n - 1)
            pos = pos + n - 1
        end
        pos = pos + 1
    end
    out[#out + 1] = '"'
    return concat(out)
end

--- json_value appends v to out as JSON: a table whose keys are 1 to n is
--- an array, and any other table an object with its keys sorted. It
--- returns nil, or an error message.
--- @param out string[]
--- @param v any
--- @return string? err
local function json_value(out, v)
    local t = type(v)
    if t == 'string' then
        local s, err = json_string(v)
        if not s then
            return err
        end
        out[#out + 1] = s
    elseif t == 'number' then
        -- an integer without a fraction on every runtime
        local integral = v == v and v % 1 == 0
        out[#out + 1] = integral and format('%d', v) or tostring(v)
    elseif t == 'boolean' then
        out[#out + 1] = tostring(v)
    elseif t == 'nil' then
        out[#out + 1] = 'null'
    elseif t == 'table' then
        local n = #v
        local keys = {}
        for k in pairs(v) do
            if type(k) ~= 'number' or k < 1 or k > n or k % 1 ~= 0 then
                keys[#keys + 1] = tostring(k)
            end
        end
        if #keys == 0 then
            out[#out + 1] = '['
            for i = 1, n do
                if i > 1 then
                    out[#out + 1] = ','
                end
                local err = json_value(out, v[i])
                if err then
                    return err
                end
            end
            out[#out + 1] = ']'
        else
            sort(keys)
            out[#out + 1] = '{'
            for i, k in ipairs(keys) do
                if i > 1 then
                    out[#out + 1] = ','
                end
                out[#out + 1] = json_string(k) or '""'
                out[#out + 1] = ':'
                local err = json_value(out, v[k])
                if err then
                    return err
                end
            end
            out[#out + 1] = '}'
        end
    else
        return 'a value of type ' .. t .. ' cannot be written as JSON'
    end
    return nil
end

--- json returns the result of a parse as JSON, or nil and an error message.
--- @param result table
--- @return string? json
--- @return string? err
local function json(result)
    local compiled = result.grammar
    local kinds = {}
    for i, kind in ipairs(compiled.kinds) do
        kinds[i] = {
            name = kind.name,
            category = kind.category,
            skip = kind.skip == true,
        }
    end
    local out = {
        '{"grammar":{"name":',
    }
    local err = json_value(out, compiled.name)
    if not err then
        out[#out + 1] = ',"version":'
        err = json_value(out, compiled.version)
    end
    if not err then
        out[#out + 1] = '},\n"kinds":'
        err = json_value(out, kinds)
    end
    if err then
        return nil, err
    end
    out[#out + 1] = ',\n"events":['
    local events = result.events
    for i = 1, result.count * 4 do
        out[#out + 1] = (i > 1 and ',' or '') .. format('%d', events[i])
    end
    out[#out + 1] = '],\n"errors":'
    err = json_value(out, result.errors or {})
    if err then
        return nil, err
    end
    out[#out + 1] = '}\n'
    return concat(out)
end

--- tree returns the result of a parse as lines: a rule with its children
--- indented under it, a named token as its name and text, and a symbol or
--- a keyword as its text.
--- @param result table
--- @return string
local function tree(result)
    local kinds, events, source = result.grammar.kinds, result.events,
                                  result.source
    local out = {}
    local depth = 0
    for i = 1, result.count do
        local base = (i - 1) * 4
        local op, kind = events[base + 1], kinds[events[base + 2]]
        if op == EXIT then
            depth = depth - 1
        else
            local line
            if op == ENTER then
                line = kind.name
            elseif op == TOKEN then
                local text = quote(sub(source, events[base + 3],
                                       events[base + 4] - 1))
                if kind.category == 'symbol' or kind.category == 'keyword' then
                    line = text
                else
                    line = kind.name .. ' ' .. text
                end
            end
            if line then
                out[#out + 1] = ('  '):rep(depth) .. line .. '\n'
            end
            if op == ENTER then
                depth = depth + 1
            end
        end
    end
    return concat(out)
end

--- parse writes the result of parsing a file, or the standard input.
local function parse(env, args)
    local fmt = 'json'
    local rest = {}
    local i = 1
    while i <= #args do
        local a = args[i]
        if a == '--format' then
            fmt = args[i + 1]
            if fmt ~= 'json' and fmt ~= 'tree' then
                return nil
            end
            i = i + 2
        else
            rest[#rest + 1] = a
            i = i + 1
        end
    end
    if #rest < 1 or #rest > 2 then
        return nil
    end
    local compiled, code = compiled_grammar(env, rest[1])
    if not compiled then
        return code
    end
    local pathname = rest[2]
    local source, err
    if pathname then
        source, err = read(env, pathname)
        if not source then
            env.stderr:write(err, '\n')
            return 2
        end
    else
        source = env.stdin:read('*a') or ''
        pathname = '-'
    end
    local result
    result, err = lexogram.parse(compiled, source)
    if not result then
        env.stderr:write(format('%s:%d:%d: %s\n', pathname, err.line,
                                err.column, err.message))
        return 1
    end
    if fmt == 'tree' then
        env.stdout:write(tree(result))
        return 0
    end
    local text
    text, err = json(result)
    if not text then
        env.stderr:write(err, '\n')
        return 2
    end
    env.stdout:write(text)
    return 0
end

local COMMANDS = {
    check = check,
    merge = merge,
    compile = compile,
    parse = parse,
}

--- main runs the command of the arguments args and returns the exit code.
--- env holds stdin, stdout and stderr (file handles) and open (io.open);
--- each defaults to that of the io library.
--- @param args string[]
--- @param env table?
--- @return integer code
local function main(args, env)
    env = env or {}
    env = {
        stdin = env.stdin or io.stdin,
        stdout = env.stdout or io.stdout,
        stderr = env.stderr or io.stderr,
        open = env.open or io_open,
    }
    local command = args[1]
    if command == '-h' or command == '--help' or command == 'help' then
        env.stdout:write(USAGE)
        return 0
    end
    local fn = COMMANDS[command]
    local code
    if fn then
        local rest = {}
        for i = 2, #args do
            rest[i - 1] = args[i]
        end
        code = fn(env, rest)
    end
    if not code then
        env.stderr:write(USAGE)
        return 2
    end
    return code
end

return {
    main = main,
}
