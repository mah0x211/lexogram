-- lexogram: public entry point of the lexogram library.
-- load(pathname) loads a grammar file and resolves the grammar it
-- extends and the mixins it embeds (see lexogram.loader and
-- lexogram.extend),
-- check(grammar) returns the diagnostics of a grammar table (see
-- lexogram.check), compile(grammar) compiles it into plain data (see
-- lexogram.compile), tokenize(compiled, source, pos, mode) finds the
-- token at a position (see lexogram.tokenizer; source is a string or an
-- input of input(source), which keeps the values of the lookaheads for
-- repeated calls) and parse(compiled, source) returns the event array of a
-- source (see lexogram.analyzer).
-- merge(pathname) returns the Lua source of the grammar file merged with
-- the grammars it extends, which extends no grammar (see lexogram.source).
-- dump(compiled) returns the Lua source of a compiled grammar to save, and
-- undump(text) reads it back without checking and compiling the grammar
-- again (see lexogram.dump).
local type = type
local error = error
local analyzer = require('lexogram.analyzer')
local loader = require('lexogram.loader')
local check = require('lexogram.check')
local compile = require('lexogram.compile')
local tokenizer = require('lexogram.tokenizer')
local write = require('lexogram.source').write
local dump = require('lexogram.dump')

--- merge loads the grammar file at pathname, merges it with the grammars it
--- extends and the mixins it embeds, and returns the Lua source text of the
--- result, which extends no grammar and loads back into an equal table, nil
--- and the warnings of the mixins (see lexogram.loader); or nil and an
--- error message.
--- @param pathname string a grammar file or "lexogram:name"
--- @return string? source
--- @return string? err
--- @return table[]? warnings
local function merge(pathname)
    if type(pathname) ~= 'string' then
        error('pathname must be string, got ' .. type(pathname), 2)
    end
    local grammar, err, warnings = loader.load(pathname)
    if not grammar then
        return nil, err
    end
    local header = {
        'Generated by lexogram.merge from ' .. pathname .. '.',
    }
    local name, version = grammar.name, grammar.version
    if type(name) == 'string' and type(version) == 'string' then
        header[2] = 'Grammar ' .. name .. ' ' .. version .. '.'
    end
    local source
    source, err = write(grammar, header)
    if not source then
        return nil, pathname .. ': ' .. err
    end
    return source, nil, warnings
end

return {
    load = loader.load,
    merge = merge,
    dump = dump.dump,
    undump = dump.undump,
    check = check.check,
    compile = compile.compile,
    tokenize = tokenizer.tokenize,
    input = tokenizer.input,
    parse = analyzer.parse,
}
