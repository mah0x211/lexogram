-- lexogram.dump: writes a compiled grammar as Lua source text, and reads
-- the text back (lexogram.dump and lexogram.undump).
--
-- The text is a chunk that returns { format = FORMAT, compiled = <the
-- compiled grammar> }, written by lexogram.source, so the same compiled
-- grammar gives the same text on every runtime. FORMAT is the revision of
-- the layout of a compiled grammar (see lexogram.compile), which is
-- internal and may change from one version of lexogram to the next: undump
-- rejects the text of another revision, and the grammar is compiled again.
--
-- undump runs the text with an empty environment, as grammar files are
-- run. The isolation keeps the text declarative, but it is no security
-- sandbox: the text must be trusted as code is. undump checks the shape of
-- the top-level fields, not the tables of the automata.
local type = type
local error = error
local ipairs = ipairs
local pcall = pcall
local tostring = tostring
local load_text = require('lexogram.compat').load_text
local write = require('lexogram.source').write
local HISTORY = require('lexogram.version').HISTORY

-- the revision of the layout of a compiled grammar
local FORMAT = 1

-- the fields of a compiled grammar that undump checks, with their types
local FIELDS = {
    {
        'kinds',
        'table',
    },
    {
        'names',
        'table',
    },
    {
        'literals',
        'table',
    },
    {
        'lexer',
        'table',
    },
    {
        'syntax',
        'table',
    },
}

--- dump returns the Lua source text of the compiled grammar compiled, which
--- undump reads back, or nil and an error message for a value that cannot
--- be written (see lexogram.source).
--- @param compiled table
--- @return string? text
--- @return string? err
local function dump(compiled)
    if type(compiled) ~= 'table' then
        error('compiled must be table, got ' .. type(compiled), 2)
    end
    local header = {
        'Generated by lexogram.dump.',
    }
    local name, version = compiled.name, compiled.version
    if type(name) == 'string' and type(version) == 'string' then
        header[2] = 'Grammar ' .. name .. ' ' .. version .. '.'
    end
    return write({
        format = FORMAT,
        compiled = compiled,
    }, header)
end

--- known returns true if v is a revision of the specification in HISTORY.
--- @param v any
--- @return boolean
local function known(v)
    for _, h in ipairs(HISTORY) do
        if v == h then
            return true
        end
    end
    return false
end

--- undump returns the compiled grammar that the text written by dump
--- holds, or nil and an error message.
--- @param text string
--- @return table? compiled
--- @return string? err
local function undump(text)
    if type(text) ~= 'string' then
        error('text must be string, got ' .. type(text), 2)
    end
    local fn, err = load_text(text, '=lexogram.undump', {})
    if not fn then
        return nil, err
    end
    local ok, res = pcall(fn)
    if not ok then
        return nil, tostring(res)
    elseif type(res) ~= 'table' or res.format == nil then
        return nil, 'not a compiled grammar written by lexogram.dump'
    elseif res.format ~= FORMAT then
        return nil,
               'a compiled grammar of format ' .. tostring(res.format) ..
                   ', expected ' .. FORMAT .. ': compile the grammar again'
    end
    local compiled = res.compiled
    if type(compiled) ~= 'table' then
        return nil, 'compiled must be a table, got ' .. type(compiled)
    elseif not known(compiled.lexogram) then
        return nil,
               'compiled.lexogram must be a revision of the' ..
                   ' specification, got ' .. tostring(compiled.lexogram)
    end
    for _, field in ipairs(FIELDS) do
        local v = compiled[field[1]]
        if type(v) ~= field[2] then
            return nil, 'compiled.' .. field[1] .. ' must be a ' .. field[2] ..
                       ', got ' .. type(v)
        end
    end
    for _, key in ipairs({
        'name',
        'version',
    }) do
        local v = compiled[key]
        if v ~= nil and type(v) ~= 'string' then
            return nil,
                   'compiled.' .. key .. ' must be a string, got ' .. type(v)
        end
    end
    return compiled
end

return {
    FORMAT = FORMAT,
    dump = dump,
    undump = undump,
}
