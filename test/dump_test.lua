local testcase = require('testcase')
local assert = require('assert')
local lexogram = require('lexogram')
local dump = require('lexogram.dump')

local shared = dofile(debug.getinfo(1, 'S').source:match('^@(.-)[^/]*$') ..
                          'grammars/shared.lua')
local without_hook = shared.without_hook

-- grammars that use each part of a compiled grammar: delimited tokens
-- (lua51), leading tokens (lua54_shebang), stages and lookaheads (luajit),
-- trials and two tokens ahead (c99)
local CASES = {
    {
        'lexogram:lua51',
        'local s = [==[x]==] -- c\nprint(s)',
    },
    {
        'lexogram:lua54_shebang',
        '#!/usr/bin/lua\nlocal x <const> = 1',
    },
    {
        'lexogram:luajit',
        'local n = 0x1p4 + 10ULL + 2i',
    },
    {
        'lexogram:c99',
        '#include <stdio.h>\nint main(void) { T *p; return (int)p; }',
    },
}

-- the events of a parse as one array
local function events_of(compiled, source)
    local result = assert(lexogram.parse(compiled, source))
    local out = {}
    for i = 1, result.count * 4 do
        out[i] = result.events[i]
    end
    return out
end

function testcase.lexogram_exports_dump_and_undump()
    assert.rawequal(lexogram.dump, dump.dump)
    assert.rawequal(lexogram.undump, dump.undump)
end

function testcase.undump_reads_back_what_dump_writes()
    for _, case in ipairs(CASES) do
        local compiled = assert(shared.compile(case[1]))
        local text = assert(without_hook(dump.dump, compiled))
        -- the name and version of the grammar head the text
        local grammar = compiled.name .. ' ' .. compiled.version
        local head = '%-%- Grammar ' .. grammar:gsub('%p', '%%%0') .. '%.\n'
        assert.match(text, '^%-%- Generated by lexogram%.dump%.\n' .. head,
                     false)
        local back, err = without_hook(dump.undump, text)
        assert.is_nil(err)
        assert.equal(back, compiled)
        -- the same compiled grammar gives the same text
        assert.equal(without_hook(dump.dump, back), text)
        assert.equal(events_of(back, case[2]), events_of(compiled, case[2]))
    end
end

function testcase.dump_reports_values_that_cannot_be_written()
    local compiled = assert(shared.compile('lexogram:lua51'))
    compiled.lexer = print
    local text, err = dump.dump(compiled)
    assert.is_nil(text)
    assert.match(err, 'compiled.lexer: a value of type function', true)
    assert.match(assert.throws(dump.dump, 'x'),
                 'compiled must be table, got string', true)
end

function testcase.undump_reports_text_that_is_not_a_dumped_grammar()
    local function err_of(text)
        local compiled, err = dump.undump(text)
        assert.is_nil(compiled)
        assert.is_string(err)
        return err
    end
    -- a valid compiled grammar to change
    local function text_with(change)
        local compiled = assert(shared.compile('lexogram:lua51'))
        change(compiled)
        return '-- a changed grammar\nreturn ' ..
                   assert(dump.dump(compiled)):match('\nreturn (.*)$')
    end

    assert.match(err_of('return {'), 'lexogram.undump:1:', true)
    -- the text runs with an empty environment
    assert.match(err_of('return print()'), 'lexogram.undump:1:', true)
    assert.equal(err_of('return 1'),
                 'not a compiled grammar written by lexogram.dump')
    assert.equal(err_of('return {}'),
                 'not a compiled grammar written by lexogram.dump')
    assert.equal(err_of('return { format = ' .. (dump.FORMAT + 1) .. ' }'),
                 'a compiled grammar of format ' .. (dump.FORMAT + 1) ..
                     ', expected ' .. dump.FORMAT ..
                     ': compile the grammar again')
    assert.equal(err_of('return { format = ' .. dump.FORMAT .. ' }'),
                 'compiled must be a table, got nil')
    assert.equal(err_of(text_with(function(c)
        c.lexogram = '2000.01.01.1'
    end)), 'compiled.lexogram must be a revision of the specification,' ..
                     ' got 2000.01.01.1')
    assert.equal(err_of(text_with(function(c)
        c.syntax = nil
    end)), 'compiled.syntax must be a table, got nil')
    assert.equal(err_of(text_with(function(c)
        c.name = 1
    end)), 'compiled.name must be a string, got number')
    assert.match(assert.throws(dump.undump, {}),
                 'text must be string, got table', true)
end
