local testcase = require('testcase')
local assert = require('assert')
local lexogram = require('lexogram')
local loader = require('lexogram.loader')
local check = require('lexogram.check')
local compile = require('lexogram.compile')
local tokenizer = require('lexogram.tokenizer')

-- the testcase runner executes a test file with its own directory as the
-- working directory, so the repository root is one level up
local ROOT = '../'

function testcase.load_is_the_loader_function()
    assert.rawequal(lexogram.load, loader.load)
end

function testcase.load_loads_grammar_file()
    local grammar, err = lexogram.load(ROOT .. 'test/fixtures/loader/plain.lua')

    assert.is_nil(err)
    assert.equal(grammar, {
        name = 'plain',
        list = {
            'a',
            'b',
        },
    })
end

function testcase.check_is_the_check_function()
    assert.rawequal(lexogram.check, check.check)
end

function testcase.check_returns_diagnostics_of_loaded_grammar()
    local grammar = assert(lexogram.load(ROOT ..
                                             'test/fixtures/loader/plain.lua'))

    local diagnostics = lexogram.check(grammar)

    assert.equal(diagnostics, {
        {
            severity = 'error',
            code = 'missing_field',
            path = 'lexogram',
            message = 'required field lexogram is missing',
        },
        {
            severity = 'error',
            code = 'missing_field',
            path = 'version',
            message = 'required field version is missing',
        },
        {
            severity = 'error',
            code = 'missing_field',
            path = 'start',
            message = 'required field start is missing',
        },
        {
            severity = 'error',
            code = 'missing_field',
            path = 'tokens',
            message = 'required field tokens is missing',
        },
        {
            severity = 'error',
            code = 'missing_field',
            path = 'rules',
            message = 'required field rules is missing',
        },
        {
            severity = 'error',
            code = 'unknown_field',
            path = 'list',
            message = 'unknown field list',
        },
    })
end

function testcase.compile_is_the_compile_function()
    assert.rawequal(lexogram.compile, compile.compile)
end

function testcase.tokenize_is_the_tokenize_function()
    assert.rawequal(lexogram.tokenize, tokenizer.tokenize)
end

function testcase.merge_writes_a_grammar_that_extends_none()
    local pathname = ROOT .. 'test/fixtures/extends/grandchild.lua'
    local src, err = lexogram.merge(pathname)

    assert.is_nil(err)
    assert.match(src,
                 '^%-%- Generated by lexogram%.merge from ' ..
                     pathname:gsub('%p', '%%%0') ..
                     '%.\n%-%- Grammar grandchild 1%.0%.0%.\nreturn {\n', false)
    assert.not_match(src, '\n    extends = ', true)
    -- the source loads back into the merged grammar
    local fn = assert((loadstring or load)(src))
    assert.equal(fn(), lexogram.load(pathname))
    -- a built-in grammar is merged by its name
    package.preload['lexogram.grammars.mini'] = function()
        return function()
            return {
                lexogram = '2026.11.15.1',
                name = 'mini',
                version = '1.0.0',
                start = 'chunk',
                tokens = {
                    name = '[a-z]+',
                },
                rules = {
                    chunk = 'name*',
                },
            }
        end
    end
    src = assert(lexogram.merge('lexogram:mini'))
    package.preload['lexogram.grammars.mini'] = nil
    package.loaded['lexogram.grammars.mini'] = nil
    assert.match(src,
                 '^%-%- Generated by lexogram%.merge from lexogram:mini%.\n',
                 false)
    assert.equal((loadstring or load)(src)().rules, {
        chunk = 'name*',
    })
end

function testcase.merge_reports_errors()
    local src, err = lexogram.merge(ROOT ..
                                        'test/fixtures/extends/bad_merge.lua')
    assert.is_nil(src)
    assert.match(err, 'tokens.name: already exists', true)

    -- a grammar file may hold a value that has no source text
    src, err =
        lexogram.merge(ROOT .. 'test/fixtures/extends/function_value.lua')
    assert.is_nil(src)
    assert.equal(err, ROOT .. 'test/fixtures/extends/function_value.lua:' ..
                     ' tokens.f: a value of type function cannot be written')

    assert.match(select(2, pcall(lexogram.merge, 1)),
                 'pathname must be string, got number', true)
end
